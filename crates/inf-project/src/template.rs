    /// **Every 3D template ships the starter character, and it ships all of it**
    /// (SK1c).
    ///
    /// Two claims, and the second is the one a hand-written `include_bytes!`
    /// list cannot make for itself: the table is the WHOLE sample folder. A
    /// character's assets name each other by GUID, so a scaffold missing one
    /// sidecar is a project whose rig resolves and whose clips do not — and the
    /// symptom is a character that stands still, three layers away from the
    /// list somebody forgot to add a line to.
    ///
    /// The folder is read off disk rather than mirrored here, so the two cannot
    /// drift; `README.md`, `camera.toml` and `input.toml` are the documented
    /// exceptions and are named, not pattern-matched away.
    #[test]
    fn every_3d_template_ships_the_whole_starter_character() {
        const SKIPPED: [&str; 3] = ["README.md", "camera.toml", "input.toml"];
        // **BOTH committed bodies** (wave CHAR1a.2). The union, because
        // `STARTER_CHARACTER` scaffolds both and a gate that read one folder
        // would go green on a template that shipped half a pair.
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../samples");
        let dirs = [
            root.join("starter-character"),
            root.join("starter-character-f"),
        ];
        let mut on_disk: Vec<String> = Vec::new();
        for dir in &dirs {
            on_disk.extend(
                std::fs::read_dir(dir)
                    .unwrap_or_else(|e| panic!("no {}: {e}", dir.display()))
                    .filter_map(|e| e.ok())
                    .filter(|e| e.file_type().map(|t| t.is_file()).unwrap_or(false))
                    .map(|e| e.file_name().to_string_lossy().into_owned())
                    .filter(|n| !SKIPPED.contains(&n.as_str())),
            );
        }
        on_disk.sort();

        let mut shipped: Vec<String> = STARTER_CHARACTER
            .iter()
            .map(|(rel, _)| {
                rel.strip_prefix("Characters/")
                    .expect("the starter character scaffolds under Characters/")
                    .to_string()
            })
            .collect();
        shipped.sort();
        assert_eq!(
            shipped, on_disk,
            "`STARTER_CHARACTER` is not the sample folder — a character's assets \
             name each other by GUID, so a missing entry is a project whose \
             clips resolve to nothing"
        );

        // …and the bytes really are the committed ones, not a stale copy from
        // whenever the list was written. Whichever folder holds the file — the
        // scaffold flattens both into `Characters/`, so the name is the key.
        for (rel, bytes) in STARTER_CHARACTER {
            let name = rel.strip_prefix("Characters/").unwrap();
            let path = dirs
                .iter()
                .map(|d| d.join(name))
                .find(|p| p.is_file())
                .unwrap_or_else(|| panic!("{name} is in `STARTER_CHARACTER` and on no disk"));
            assert_eq!(
                &std::fs::read(&path).unwrap(),
                bytes,
                "{name} is stale in `STARTER_CHARACTER`"
            );
        }

        // Which templates get it, asserted as a partition rather than as three
        // positives: a fourth 3D template added without a line here would
        // otherwise ship nothing and nothing would say so.
        for t in ProjectTemplate::all() {
            let content = t.starter_content();
            match t {
                ProjectTemplate::Platformer2d => assert!(
                    content.iter().all(|(n, _)| n.starts_with("Coyote")),
                    "the 2D platformer scaffolds a 3D biped"
                ),
                _ => assert_eq!(
                    content.len(),
                    STARTER_CHARACTER.len(),
                    "{t:?} does not ship the starter character"
                ),
            }
        }
    }


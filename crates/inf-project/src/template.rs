/// A template's committed boot scene: the payload **and its sidecar**.
///
/// The sidecar is not decoration. `AssetDb` synthesizes a **content-derived**
/// GUID for a loose payload that has none, so a level scaffolded without one
/// gets a different identity in every project it is scaffolded into — and the
/// `ActorClass` bindings inside it name asset GUIDs that must resolve. The
/// scaffold wrote the payload alone until IB-7; this type is why it cannot
/// again.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StarterLevel {
    /// The file name written under the project's levels root.
    pub file_name: &'static str,
    /// The `.inf_lvl` bincode payload.
    pub payload: &'static [u8],
    /// The `.inf_lvl.toml` asset sidecar (GUID, kind, content hash, deps).
    pub sidecar: &'static [u8],
}

/// The result of scaffolding: where the project was created.
#[derive(Debug, Clone)]
pub struct Scaffolded {
    pub root: PathBuf,
    pub crate_name: String,
    pub manifest: ProjectManifest,
}

/// Scaffold a new project named `name` from `template` inside `parent`. The
/// project directory is `parent/<sanitized-name>`; it must not already exist
/// (or must be empty). Returns the created root.
pub fn scaffold(parent: &Path, name: &str, template: ProjectTemplate) -> Result<Scaffolded> {
    let dir_name = sanitize_dir(name);
    let crate_name = sanitize_crate(name);
    let root = parent.join(&dir_name);

    if root.exists() && std::fs::read_dir(&root)?.next().is_some() {
        return Err(ProjectError::Other(format!(
            "{} already exists and is not empty",
            root.display()
        )));
    }

    let manifest = ProjectManifest::new(name, template.slug());
    manifest.save(&root)?;

    // User cargo crate.
    write(&root.join("Cargo.toml"), &cargo_toml(&crate_name))?;
    write(&root.join("src/lib.rs"), &template.starter_lib(&crate_name))?;
    // **`src/blueprints/` exists from day one** (Wave D), with an index that
    // compiles. `lib.rs` declares `pub mod blueprints;` above, so a project
    // scaffolded and immediately built has to find something there — an empty
    // directory would make every new project fail `cargo build` until its first
    // blueprint, which is the worst possible first impression.
    //
    // Only NEW projects get this. An existing project's hand-written `lib.rs` is
    // not edited behind its author's back; the editor's Code tab creates the
    // directory and the index on first use and the author adds the one line.
    write(
        &root.join("src/blueprints/mod.rs"),
        "// @generated by Infini Engine — edits may be overwritten.\n\
         //\n\
         // One `pub mod` per generated blueprint class. Rebuilt from the directory\n\
         // whenever the editor writes a class, so a deleted one's line goes with it.\n",
    )?;

    // Content root + the levels root INSIDE it (IB-7). Kept in git with a
    // placeholder so an empty project still round-trips through a clone.
    let content_root = root.join(&manifest.content_dir);
    let levels_root = content_root.join(&manifest.levels_dir);
    write(&content_root.join(".gitkeep"), "")?;
    write(&levels_root.join(".gitkeep"), "")?;

    // The boot scene — payload AND sidecar, so the level keeps its identity and
    // its bindings resolve. Every template ships one (IB-7).
    let level = template.starter_level();
    let level_path = levels_root.join(level.file_name);
    std::fs::create_dir_all(&levels_root)?;
    inf_asset::write_atomically(&level_path, level.payload)?;
    inf_asset::write_atomically(
        &levels_root.join(format!("{}.toml", level.file_name)),
        level.sidecar,
    )?;

    // The example script, under `Content/Scripts/` (the SCRIPT1b layout ruling —
    // see `Project::scripts_root`). Written as text through the same atomic door
    // as everything else; the asset database synthesises its sidecar on the
    // first scan, from the content hash, so the GUID is a function of the bytes.
    {
        let (rel, src) = template.starter_script();
        let path = content_root.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        write(&path, src)?;
    }

    // …and whatever the boot scene binds, beside it under the content root.
    for (rel, bytes) in template.starter_content() {
        let path = content_root.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        inf_asset::write_atomically(&path, *bytes)?;
    }

    write(&root.join(".gitignore"), GITIGNORE)?;
    write(&root.join(".gitattributes"), GITATTRIBUTES)?;
    write(
        &root.join("README.md"),
        &format!(
            "# {name}\n\nAn Infini Engine project ({}).\n\nOpen it in Infini Engine, or build the gameplay crate with `cargo build`.\n",
            template.label()
        ),
    )?;

    Ok(Scaffolded {
        root,
        crate_name,
        manifest,
    })
}

fn write(path: &Path, contents: &str) -> Result<()> {
    inf_asset::write_atomically(path, contents)?;
    Ok(())
}

fn cargo_toml(crate_name: &str) -> String {
    format!(
        "[package]\n\
         name = \"{crate_name}\"\n\
         version = \"0.1.0\"\n\
         edition = \"2021\"\n\
         \n\
         [lib]\n\
         crate-type = [\"lib\"]\n\
         \n\
         [dependencies]\n"
    )
}

const GITIGNORE: &str = "/target\n/Content/.inf/\n*.inf_lvl.autosave\ncrash-recovery.inf_lvl\n";

/// The `.gitattributes` every scaffolded project gets — **SCRIPT1b's carried
/// item 5, closed by the SCRIPT1b audit rather than carried again.**
///
/// The engine's own `.gitattributes` has had `*.infini -text` since the wave
/// that found the reason, and the ledger's carried entry said *"a user's project
/// inherits the same rule and nothing tells them so yet"*. That understated it
/// once the layout ruling landed: every template now scaffolds
/// `Content/Scripts/Example.infini` with **no committed sidecar**, so its asset
/// GUID is synthesised from its **content hash** on the first scan — and a hash
/// is over bytes. A user who commits the scaffolded project and clones it on the
/// other operating system gets git's line-ending conversion, a different byte
/// stream, a different GUID for the same program, and every `ActorClass` binding
/// pointing at nothing. Telling them is not enough when the file is already
/// there on day one; the rule ships with the project.
///
/// Scoped to what the reasoning covers: only the file kinds whose **identity is
/// their bytes** live under a user's content root. `.inf_lvl` and the other
/// binary payloads are already binary to git by content detection; `.infini` is
/// the one that reads as text and must not be treated as such.
const GITATTRIBUTES: &str = "\
# InfiniScript source is text a human writes, and `-text` is deliberate: the
# LEXER normalises CRLF, a lone CR and a byte-order mark, so what a script MEANS
# is insensitive to all three. What cannot be normalised is the file's IDENTITY
# - a `.infini` with no committed sidecar takes its asset GUID from its CONTENT
# HASH, and a hash is over bytes. Let git rewrite the line endings and the same
# program gets a different GUID on Windows than on Linux, with every level
# binding pointing at nothing.
*.infini -text
";

/// A filesystem-safe directory name (spaces → hyphens, alnum/-/_ kept).
pub fn sanitize_dir(name: &str) -> String {
    let s: String = name
        .trim()
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '-' || c == '_' {
                c
            } else {
                '-'
            }
        })
        .collect();
    let trimmed = s.trim_matches('-').to_string();
    if trimmed.is_empty() {
        "InfinityProject".to_string()
    } else {
        trimmed
    }
}

/// A valid `snake_case` crate name.
pub fn sanitize_crate(name: &str) -> String {
    let mut out = String::new();
    for c in name.chars() {
        if c.is_alphanumeric() {
            out.extend(c.to_lowercase());
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    let trimmed = out.trim_matches('_').to_string();
    if trimmed.is_empty() || trimmed.chars().next().unwrap().is_numeric() {
        format!("game_{trimmed}")
    } else {
        trimmed
    }
}


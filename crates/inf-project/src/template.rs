//! Project templates + scaffolding.
//!
//! `inf new` (and the editor's New Project dialog) scaffold a project directory
//! from a template: a real user cargo crate (where hand-written gameplay + the
//! P6-generated Rust will live), the `inf.toml` manifest, the content root, and
//! **a boot scene under `Content/Levels/`**.
//!
//! # The IB-7 ruling
//!
//! All four templates scaffold a boot level, and it lands where `inf cook`
//! looks. Before the island phase, two of the four scaffolded no level at all
//! and the other two scaffolded one into `<root>/Levels/` — a directory the cook
//! never opens — so **four of four produced a project `inf cook` refused**. See
//! [`Project::levels_root`](crate::Project::levels_root) for why levels are
//! content rather than a parallel root, and `inf-player`'s `first_run_path` for
//! the arm that runs `new` → `cook` → the shipped player on every template.

use std::path::{Path, PathBuf};

use crate::error::{ProjectError, Result};
use crate::manifest::ProjectManifest;

/// A first-run project template.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProjectTemplate {
    /// Empty 3D scene.
    Blank3d,
    /// 2D side-scroller starter.
    Platformer2d,
    /// First-person starter.
    FirstPerson,
    /// Hybrid 2.5D starter: a 3D ground plane with billboarded sprites (P8.4b).
    Hybrid25d,
}

impl ProjectTemplate {
    pub fn slug(self) -> &'static str {
        match self {
            ProjectTemplate::Blank3d => "blank-3d",
            ProjectTemplate::Platformer2d => "2d-platformer",
            ProjectTemplate::FirstPerson => "first-person",
            ProjectTemplate::Hybrid25d => "hybrid-2.5d",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            ProjectTemplate::Blank3d => "Blank 3D",
            ProjectTemplate::Platformer2d => "2D Platformer",
            ProjectTemplate::FirstPerson => "First Person",
            ProjectTemplate::Hybrid25d => "Hybrid 2.5D",
        }
    }

    pub fn description(self) -> &'static str {
        match self {
            ProjectTemplate::Blank3d => "An empty 3D scene — a clean slate.",
            ProjectTemplate::Platformer2d => "A 2D side-scroller starter.",
            ProjectTemplate::FirstPerson => "A first-person starter.",
            ProjectTemplate::Hybrid25d => {
                "A 2.5D scene: a 3D ground plane with billboarded sprites."
            }
        }
    }

    pub fn from_slug(slug: &str) -> Option<Self> {
        Self::all().iter().copied().find(|t| t.slug() == slug)
    }

    pub fn all() -> &'static [ProjectTemplate] {
        &[
            ProjectTemplate::Blank3d,
            ProjectTemplate::Platformer2d,
            ProjectTemplate::FirstPerson,
            ProjectTemplate::Hybrid25d,
        ]
    }

    /// The committed starter `.inf_lvl` this template scaffolds into
    /// [`Project::levels_root`](crate::Project::levels_root) — its **boot
    /// scene**.
    ///
    /// # Every template ships one, and that is the IB-7 ruling's other half
    ///
    /// Two of the four used to return `None`, and a project with no level is a
    /// project `inf cook` refuses: *"no levels in cook — the build has no boot
    /// scene"*. Moving levels under `Content/` fixes where a level is found; it
    /// does not conjure one for a template that scaffolds none. So Blank 3D and
    /// 2D Platformer got starter scenes (`samples::blank3d_scene`,
    /// `samples::platformer_scene`), and `inf new` → `inf cook` → run is now a
    /// property of **all four**, asserted by `inf-player`'s `first_run_path`.
    ///
    /// All four payloads are generated by `inf_editor_core::samples` and blessed
    /// by `committed_sample_matches_generators`, so there is one definition of
    /// each scene in this repository and these bytes are locked to it.
    pub fn starter_level(self) -> StarterLevel {
        match self {
            ProjectTemplate::Blank3d => StarterLevel {
                file_name: "Main.inf_lvl",
                payload: include_bytes!("../../../templates/blank-3d/Blank.inf_lvl"),
                sidecar: include_bytes!("../../../templates/blank-3d/Blank.inf_lvl.toml"),
            },
            ProjectTemplate::Platformer2d => StarterLevel {
                file_name: "Main.inf_lvl",
                payload: include_bytes!("../../../templates/2d-platformer/Platformer.inf_lvl"),
                sidecar: include_bytes!("../../../templates/2d-platformer/Platformer.inf_lvl.toml"),
            },
            ProjectTemplate::FirstPerson => StarterLevel {
                file_name: "Main.inf_lvl",
                payload: include_bytes!("../../../templates/first-person/FirstPerson.inf_lvl"),
                sidecar: include_bytes!("../../../templates/first-person/FirstPerson.inf_lvl.toml"),
            },
            ProjectTemplate::Hybrid25d => StarterLevel {
                file_name: "Main.inf_lvl",
                payload: include_bytes!("../../../templates/hybrid-2.5d/Hybrid.inf_lvl"),
                sidecar: include_bytes!("../../../templates/hybrid-2.5d/Hybrid.inf_lvl.toml"),
            },
        }
    }

    /// Extra content files scaffolded **beside** the boot level, relative to the
    /// project's content root: `(relative path, bytes)`.
    ///
    /// The 2D platformer's level carries an `ActorClass` binding, and an asset
    /// GUID with no asset behind it is a player that does not move. A template's
    /// promise is a project that runs, so what the boot scene binds ships with
    /// it.
    ///
    /// # The starter character (SK1c)
    ///
    /// Every 3D template scaffolds [`STARTER_CHARACTER`] into `Characters/`, and
    /// the reason is the same promise one step further on: the New Character
    /// wizard can build a character on demand, and until this wave nothing
    /// *shipped* one — so a new 3D project's first question ("where is the
    /// player?") had no answer that did not start with a wizard.
    ///
    /// The 2D platformer does not get it. A 161-bone biped in a side-scroller is
    /// 155 KB of content an author has to notice in order to delete, and Coyote
    /// is already that template's answer to the same question.
    ///
    /// The bytes are `include_bytes!` from `samples/starter-character`, which is
    /// generated by the New Character wizard's own door and byte-locked against
    /// it — see `inf_editor_core::samples::starter_character_files`. That is why
    /// there is no crate edge here: this crate names a *path*, not `inf-anim`.
    pub fn starter_content(self) -> &'static [(&'static str, &'static [u8])] {
        match self {
            ProjectTemplate::Platformer2d => &[
                (
                    "Coyote.inf_act",
                    include_bytes!("../../../templates/2d-platformer/Coyote.inf_act"),
                ),
                (
                    "Coyote.inf_act.toml",
                    include_bytes!("../../../templates/2d-platformer/Coyote.inf_act.toml"),
                ),
            ],
            ProjectTemplate::Blank3d
            | ProjectTemplate::FirstPerson
            | ProjectTemplate::Hybrid25d => STARTER_CHARACTER,
        }
    }

    /// The example `.infini` every template scaffolds, as `(path under the
    /// content root, source text)`.
    ///
    /// Separate from [`starter_content`](Self::starter_content) rather than
    /// appended to it, and the reason is a gate: that constant's arm
    /// (`every_3d_template_ships_the_whole_starter_character`) asserts it is
    /// *exactly* the seventeen character files, so growing it would have meant
    /// loosening the one check that keeps a template from silently shipping
    /// fewer bindings than its level names.
    ///
    /// The same for all four templates, because the script it ships is about the
    /// *language* rather than about the genre: a member variable, a `begin_play`,
    /// a `tick` with arithmetic and a branch, and the two verbs every actor has.
    /// A designer's first edit to it is the arc's whole point — save the file
    /// while Simulate runs and the change is live.
    pub fn starter_script(self) -> (&'static str, &'static str) {
        (
            "Scripts/Example.infini",
            include_str!("../../../templates/scripts/Example.infini"),
        )
    }

    fn starter_lib(self, crate_name: &str) -> String {
        let doc = match self {
            ProjectTemplate::Blank3d => "an empty 3D scene",
            ProjectTemplate::Platformer2d => "a 2D platformer",
            ProjectTemplate::FirstPerson => "a first-person game",
            ProjectTemplate::Hybrid25d => "a hybrid 2.5D scene",
        };
        format!(
            "//! `{crate_name}` — gameplay for {doc}.\n\
             //!\n\
             //! Hand-written systems live here; Infini Blueprints (Phase 6) generate\n\
             //! additional Rust into this crate and stay in sync.\n\
             //!\n\
             //! Generated blueprint code lives in `src/blueprints/` and is COMMITTED,\n\
             //! not ignored — it is what cargo compiles and what ships. The editor's\n\
             //! Code tab writes it; each file carries the graph hash it came from and\n\
             //! is rewritten when that goes stale.\n\
             \n\
             pub mod blueprints;\n\
             \n\
             /// Called once when play begins.\n\
             pub fn begin_play() {{\n    \
                 // Your setup here.\n\
             }}\n\
             \n\
             /// Called every frame with the delta time in seconds.\n\
             pub fn tick(_dt: f32) {{\n    \
                 // Your per-frame logic here.\n\
             }}\n"
        )
    }
}

